-- KaiwaTube PostgreSQL schema (isolated from public schema)
CREATE SCHEMA IF NOT EXISTS kaiwatube;

REVOKE ALL ON SCHEMA kaiwatube FROM PUBLIC;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    EXECUTE 'REVOKE ALL ON SCHEMA kaiwatube FROM anon';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    EXECUTE 'REVOKE ALL ON SCHEMA kaiwatube FROM authenticated';
  END IF;
END
$$;

CREATE TABLE IF NOT EXISTS kaiwatube.app_settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS kaiwatube.users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  display_name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'contributor', 'admin')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS kaiwatube.favorites (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES kaiwatube.users(id) ON DELETE CASCADE,
  item_type TEXT NOT NULL CHECK (item_type IN ('video', 'playlist', 'anime')),
  item_id TEXT NOT NULL,
  title TEXT NOT NULL,
  subtitle TEXT NOT NULL DEFAULT '',
  thumbnail TEXT NOT NULL DEFAULT '',
  meta_json TEXT NOT NULL DEFAULT '{}',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (user_id, item_type, item_id)
);

CREATE TABLE IF NOT EXISTS kaiwatube.community_subtitles (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  video_id TEXT NOT NULL,
  title TEXT NOT NULL,
  source_type TEXT NOT NULL CHECK (source_type IN ('ai_merged', 'uploaded')),
  author_id INTEGER REFERENCES kaiwatube.users(id) ON DELETE SET NULL,
  author_name TEXT NOT NULL,
  cues_json TEXT NOT NULL,
  cue_count INTEGER NOT NULL CHECK (cue_count > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS kaiwatube.user_subtitles (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES kaiwatube.users(id) ON DELETE CASCADE,
  video_id TEXT NOT NULL,
  title TEXT NOT NULL,
  source_type TEXT NOT NULL CHECK (source_type IN ('ai_merged', 'uploaded')),
  cues_json TEXT NOT NULL,
  cue_count INTEGER NOT NULL CHECK (cue_count > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (user_id, video_id, source_type)
);

CREATE TABLE IF NOT EXISTS kaiwatube.subtitle_reports (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  community_sub_id INTEGER NOT NULL REFERENCES kaiwatube.community_subtitles(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES kaiwatube.users(id) ON DELETE CASCADE,
  reason TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (community_sub_id, user_id)
);

CREATE TABLE IF NOT EXISTS kaiwatube.kanji_mnemonics (
  kanji TEXT PRIMARY KEY,
  han_viet TEXT NOT NULL DEFAULT '',
  decomposition TEXT NOT NULL,
  mnemonic TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_kt_community_sub_video
  ON kaiwatube.community_subtitles (video_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_kt_community_sub_author
  ON kaiwatube.community_subtitles (author_id);
CREATE INDEX IF NOT EXISTS idx_kt_user_sub_lookup
  ON kaiwatube.user_subtitles (user_id, video_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_kt_favorites_user
  ON kaiwatube.favorites (user_id, item_type, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_kt_reports_sub
  ON kaiwatube.subtitle_reports (community_sub_id);
CREATE INDEX IF NOT EXISTS idx_kt_reports_user
  ON kaiwatube.subtitle_reports (user_id);
CREATE INDEX IF NOT EXISTS idx_kt_reports_created
  ON kaiwatube.subtitle_reports (created_at DESC);

ALTER TABLE kaiwatube.app_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE kaiwatube.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE kaiwatube.favorites ENABLE ROW LEVEL SECURITY;
ALTER TABLE kaiwatube.community_subtitles ENABLE ROW LEVEL SECURITY;
ALTER TABLE kaiwatube.user_subtitles ENABLE ROW LEVEL SECURITY;
ALTER TABLE kaiwatube.subtitle_reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE kaiwatube.kanji_mnemonics ENABLE ROW LEVEL SECURITY;

